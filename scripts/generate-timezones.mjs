// Generates src/shared/timezones.ts: approximate coordinates for every IANA time zone (its principal
// city, from tzdata's zone.tab), plus the legacy aliases browsers still report ("Asia/Calcutta").
// The sky on the home screen uses them to place the sun and moon without asking for location.
//
//   node scripts/generate-timezones.mjs [/usr/share/zoneinfo]
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2] ?? '/usr/share/zoneinfo';
const zoneTab = fs.readFileSync(path.join(dir, 'zone.tab'), 'utf8');
const tzdata = fs.readFileSync(path.join(dir, 'tzdata.zi'), 'utf8');

/** ISO 6709 ±DDMM[SS]±DDDMM[SS] → [lat, lng] in degrees. */
function parseIso6709(value) {
  const match = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(value);
  if (!match) throw new Error(`Bad coordinates: ${value}`);
  const [, latSign, latD, latM, latS = '0', lngSign, lngD, lngM, lngS = '0'] = match;
  const lat = (Number(latD) + Number(latM) / 60 + Number(latS) / 3600) * (latSign === '-' ? -1 : 1);
  const lng = (Number(lngD) + Number(lngM) / 60 + Number(lngS) / 3600) * (lngSign === '-' ? -1 : 1);
  return [lat, lng];
}

const coords = new Map();
for (const line of zoneTab.split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, iso, name] = line.split('\t');
  coords.set(name, parseIso6709(iso));
}

let aliases = 0;
for (const line of tzdata.split('\n')) {
  if (!line.startsWith('L ')) continue;
  const [, target, alias] = line.split(' ');
  if (coords.has(target) && !coords.has(alias)) {
    coords.set(alias, coords.get(target));
    aliases += 1;
  }
}

const round = (n) => Math.round(n * 100) / 100;
const entries = [...coords.entries()].sort(([a], [b]) => a.localeCompare(b));
const packed = entries.map(([name, [lat, lng]]) => `${name}|${round(lat)}|${round(lng)}`).join(';');

const out = `// Generated by scripts/generate-timezones.mjs from tzdata's zone.tab — do not edit.
// ${coords.size - aliases} zones and ${aliases} legacy aliases, each placed at its principal city.

const PACKED =
  ${JSON.stringify(packed)};

let table: Map<string, readonly [number, number]> | null = null;

/** Latitude and longitude (degrees) of a time zone's principal city, if it is a known zone. */
export function timeZoneCoordinates(timeZone: string): readonly [number, number] | null {
  if (!table) {
    table = new Map();
    for (const entry of PACKED.split(';')) {
      const [name, lat, lng] = entry.split('|');
      table.set(name, [Number(lat), Number(lng)]);
    }
  }
  return table.get(timeZone) ?? null;
}
`;

const target = path.resolve('src/shared/timezones.ts');
fs.writeFileSync(target, out);
console.log(`Wrote ${target}: ${coords.size} entries (${aliases} aliases), ${(out.length / 1024).toFixed(1)} KB`);
